"""Build public/stations.json (code, name) and src/coords.js (code -> lat, lng) from the
DataMeet station list (CC0, mid-2010s), with renamed or new major stations patched by hand.

Run from site/:  python3 scripts/build_stations.py path/to/datameet/stations.json
"""
import json
import re
import sys

RENAMED = {  # old code -> (new code, current name)
    "MGS": ("DDU", "Pt Deen Dayal Upadhyaya Jn"), "ALD": ("PRYJ", "Prayagraj Jn"), "CSTM": ("CSMT", "Mumbai CSMT"),
    "BCT": ("MMCT", "Mumbai Central"), "MUV": ("BSBS", "Banaras"), "FD": ("AYC", "Ayodhya Cantt"),
    "JHS": ("VGLJ", "Virangana Lakshmibai Jhansi"), "HBJ": ("RKMP", "Rani Kamalapati (Habibganj)"),
}
NAMES = {"SMVB": "SMVT Bengaluru", "AY": "Ayodhya Dham Jn", "NDLS": "New Delhi", "DLI": "Delhi Jn (Old Delhi)",
         "ANVT": "Anand Vihar Terminal", "NZM": "Hazrat Nizamuddin", "SBC": "KSR Bengaluru City Jn",
         "MAS": "MGR Chennai Central", "LTT": "Lokmanya Tilak Terminus", "HWH": "Howrah Jn"}


def title(n):
    n = re.sub(r"\s+", " ", str(n or "")).strip().title()
    return re.sub(r"\b(Jn|Trm|Cantt|Rd|Hlt)\b", lambda m: m.group(1), n)


feats = json.load(open(sys.argv[1]))["features"]
names, coords = {}, {}
for f in feats:
    p = f["properties"]
    code = str(p.get("code") or "").strip().upper()
    if not re.fullmatch(r"[A-Z]{1,6}", code):
        continue
    names[code] = title(p.get("name"))
    g = f.get("geometry") or {}
    if g.get("coordinates"):
        lng, lat = g["coordinates"][:2]
        coords[code] = [round(lat, 3), round(lng, 3)]
for old, (new, name) in RENAMED.items():
    names.pop(old, None)
    names[new] = name
    if old in coords:
        coords[new] = coords.pop(old)
names.update(NAMES)
names = {c: n for c, n in names.items() if n}
json.dump(sorted(names.items()), open("public/stations.json", "w"), separators=(",", ":"), ensure_ascii=False)
with open("src/coords.js", "w") as out:
    out.write("// Station coordinates [lat, lng], generated by scripts/build_stations.py from the DataMeet list.\n")
    out.write("export const COORDS = " + json.dumps(coords, separators=(",", ":")) + ";\n")
print(len(names), "names,", len(coords), "coordinates")
